#!/usr/bin/env python3
"""GneissFind Lightweight Trace-as-Code QMS Verifier & RTM Generator.

Scans `qms/reqs/*.md` for requirement definitions and scans Rust (`crates/`, `cli_runner/`),
Kotlin (`android/app/src/`), and Python (`ml-pipeline/`) for `@TracesReq(...)` tags,
distinguishing production implementation references from test references.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys
from dataclasses import dataclass, field

REQ_HEADER_RE = re.compile(r"^##\s+`([A-Z]+-[A-Z0-9-]+)`:\s+(.+)$")
FIELD_RE = re.compile(r"^-\s+\*\*([A-Za-z-]+):\*\*\s+(.+)$")
TRACE_TAG_RE = re.compile(r"@TracesReq\(([^)]+)\)")
ID_SPLIT_RE = re.compile(r"[\"\'\s,]+")


@dataclass
class Requirement:
    req_id: str
    title: str
    source_file: str
    status: str = "Active"
    parents: str = "-"
    oracle: str = ""
    impl_refs: list[str] = field(default_factory=list)
    test_refs: list[str] = field(default_factory=list)


def parse_requirements(reqs_dir: pathlib.Path) -> dict[str, Requirement]:
    reqs: dict[str, Requirement] = {}
    for md_path in sorted(reqs_dir.glob("*.md")):
        current: Requirement | None = None
        for raw_line in md_path.read_text(encoding="utf-8").splitlines():
            line = raw_line.strip()
            m_hdr = REQ_HEADER_RE.match(line)
            if m_hdr:
                req_id, title = m_hdr.group(1), m_hdr.group(2)
                if req_id in reqs:
                    raise ValueError(f"Duplicate requirement ID: {req_id}")
                current = Requirement(req_id=req_id, title=title, source_file=str(md_path))
                reqs[req_id] = current
                continue
            if current is not None:
                m_fld = FIELD_RE.match(line)
                if m_fld:
                    k, v = m_fld.group(1).lower(), m_fld.group(2).strip()
                    if k == "status":
                        current.status = v
                    elif k == "parents":
                        current.parents = v
                    elif k == "oracle":
                        current.oracle = v
    return reqs


def is_test_context(rel_path: str, lines: list[str], line_idx: int) -> bool:
    p = rel_path.replace("\\", "/")
    if (
        "/test/" in p
        or "/androidTest/" in p
        or "/tests/" in p
        or p.endswith("_test.rs")
        or p.endswith("Test.kt")
        or pathlib.Path(p).name.startswith("test_")
    ):
        return True
    for look_idx in range(line_idx + 1, min(len(lines), line_idx + 6)):
        nxt = lines[look_idx].strip()
        if "#[cfg(test)]" in nxt:
            break
        if "#[test]" in nxt or "@Test" in nxt or "#[tokio::test]" in nxt or nxt.startswith("def test_"):
            return True
        if any(nxt.startswith(kw) for kw in ("pub fn ", "fn ", "pub struct ", "struct ", "impl ", "class ", "fun ", "def ")):
            break
    before = "\n".join(lines[:line_idx])
    if "#[cfg(test)]" in before:
        return True
    return False


def scan_sources(repo_root: pathlib.Path, reqs: dict[str, Requirement]) -> list[str]:
    errors: list[str] = []
    scan_roots = ["crates", "cli_runner", "android/app/src", "ml-pipeline"]
    exts = {".rs", ".kt", ".py"}

    for sub in scan_roots:
        root = repo_root / sub
        if not root.exists():
            continue
        for fpath in sorted(root.rglob("*")):
            if not fpath.is_file() or fpath.suffix not in exts:
                continue
            rel = str(fpath.relative_to(repo_root))
            lines = fpath.read_text(encoding="utf-8", errors="replace").splitlines()
            for idx, line in enumerate(lines):
                for match in TRACE_TAG_RE.finditer(line):
                    raw_ids = [tok for tok in ID_SPLIT_RE.split(match.group(1)) if tok]
                    for rid in raw_ids:
                        if rid not in reqs:
                            errors.append(f"Unknown requirement ID '{rid}' at {rel}:{idx + 1}")
                            continue
                        ref = f"{rel}:{idx + 1}"
                        if is_test_context(rel, lines, idx):
                            reqs[rid].test_refs.append(ref)
                        else:
                            reqs[rid].impl_refs.append(ref)
    return errors


def render_matrix(reqs: dict[str, Requirement]) -> str:
    out = [
        "# GneissFind Bidirectional Traceability Matrix (`docs/TRACEABILITY_MATRIX.md`)",
        "",
        "*Auto-generated by `python3 scripts/qms_verify.py` — Do not edit manually.*",
        "",
        "| Req ID | Status | Parents | Implementation Refs | Verification / Validation Refs | Gate |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for r in reqs.values():
        impl_s = "<br>".join(f"`{x}`" for x in r.impl_refs[:4]) or "*(none)*"
        if len(r.impl_refs) > 4:
            impl_s += f"<br>*(+{len(r.impl_refs) - 4} more)*"
        test_s = "<br>".join(f"`{x}`" for x in r.test_refs[:4]) or "*(none)*"
        if len(r.test_refs) > 4:
            test_s += f"<br>*(+{len(r.test_refs) - 4} more)*"

        if r.req_id.startswith("UN-"):
            gate = "VALIDATED VIA CHILDREN"
        elif r.status == "Open-M3-Sweep":
            gate = "OPEN-M3" if r.impl_refs else "MISSING-CONFIG-REF"
        else:
            gate = "PASS" if (r.impl_refs and r.test_refs) else "INCOMPLETE"
        out.append(f"| `{r.req_id}` | {r.status} | {r.parents} | {impl_s} | {test_s} | **{gate}** |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", default=".")
    parser.add_argument("--write-matrix", default="docs/TRACEABILITY_MATRIX.md")
    parser.add_argument(
        "--allow-incomplete",
        action="store_true",
        help="Report status without non-zero exit during initial bootstrap",
    )
    args = parser.parse_args()

    repo_root = pathlib.Path(args.repo_root).resolve()
    reqs_dir = repo_root / "qms" / "reqs"
    if not reqs_dir.exists():
        print(f"ERROR: Missing {reqs_dir}", file=sys.stderr)
        return 1

    reqs = parse_requirements(reqs_dir)
    errors = scan_sources(repo_root, reqs)

    for r in reqs.values():
        if r.req_id.startswith("UN-"):
            continue
        if r.status == "Open-M3-Sweep":
            if not r.impl_refs:
                errors.append(f"{r.req_id} (Open-M3-Sweep) must link to PerceptionTuningConfig struct in code")
            continue
        if r.status == "Active":
            if not r.impl_refs:
                errors.append(f"{r.req_id} missing production implementation @TracesReq(...) tag")
            if not r.test_refs:
                errors.append(f"{r.req_id} missing automated test @TracesReq(...) tag")

    matrix_md = render_matrix(reqs)
    out_path = repo_root / args.write_matrix
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(matrix_md, encoding="utf-8")

    print(f"Scanned {len(reqs)} requirements -> wrote {out_path.relative_to(repo_root)}")
    if errors:
        print(f"QMS Traceability Findings ({len(errors)}):")
        for e in errors:
            print(f"  - {e}")
        if not args.allow_incomplete:
            return 1
    else:
        print("QMS Gate: 100% PASS (All active requirements traced to code & automated tests).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
